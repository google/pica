//! ## Specifications
//! - [MAC] FiRa Consortium UWB MAC Technical Requirements
//! - [UCI] FiRa Consortium UWB Command Interface Generic Technical specification

use std::collections::HashSet;
use std::time::{Duration, Instant};

use bytes::BytesMut;

use crate::data_transfer::DataTransfer;
use crate::dl_tdoa::DlTdoaRangingRounds;
use crate::packets::uci::*;
use crate::{AppConfig, Handle, MacAddress};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum PeerKey {
    Mac(MacAddress),
    Handle(Handle),
}

pub struct Session {
    /// cf. [UCI] 7.1
    pub state: SessionState,
    /// cf. [UCI] 7.2 Table 13: 4 octets unique random number generated by application
    pub id: u32,
    pub device_handle: usize,
    pub pending_data: BytesMut,
    pub data_transfer: Option<DataTransfer>,

    pub session_type: SessionType,
    pub sequence_number: u32,
    pub ranging_count: u32,
    pub ccc_last_sts_index_used: Option<u32>,
    pub dl_tdoa_rounds: Option<DlTdoaRangingRounds>,
    pub app_config: AppConfig,
    pub in_range_peers: HashSet<PeerKey>,
    next_ranging_at: Option<Instant>,
}

impl Session {
    pub fn new(id: u32, session_type: SessionType, device_handle: usize) -> Self {
        Self {
            state: SessionState::SessionStateDeinit,
            id,
            device_handle,
            pending_data: BytesMut::new(),
            data_transfer: None,
            session_type,
            sequence_number: 0,
            ranging_count: 0,
            ccc_last_sts_index_used: None,
            dl_tdoa_rounds: None,
            app_config: AppConfig::new(session_type),
            in_range_peers: HashSet::new(),
            next_ranging_at: None,
        }
    }

    pub fn invalid_start_reason(&self) -> Option<ReasonCode> {
        self.app_config
            .invalid_start_reason()
            .or_else(|| self.dl_tdoa_invalid_start_reason())
    }

    #[must_use]
    pub fn set_state(
        &mut self,
        session_state: SessionState,
        reason_code: ReasonCode,
    ) -> Option<SessionStatusNtf> {
        if session_state == self.state {
            return None;
        }

        self.state = session_state;
        Some(SessionStatusNtf {
            session_token: self.id,
            session_state,
            reason_code,
        })
    }

    pub fn get_dst_mac_address(&self) -> impl Iterator<Item = MacAddress> + '_ {
        self.app_config.dst_mac_address()
    }

    pub fn session_type(&self) -> SessionType {
        self.session_type
    }

    pub fn is_supported_session_type(&self) -> bool {
        matches!(
            self.session_type,
            SessionType::FiraRangingSession
                | SessionType::FiraRangingAndInBandDataSession
                | SessionType::FiraDataTransferSession
                | SessionType::Ccc
                | SessionType::Aliro
        )
    }

    pub fn session_state(&self) -> SessionState {
        self.state
    }

    #[must_use]
    pub fn init(&mut self) -> Option<SessionStatusNtf> {
        self.set_state(
            SessionState::SessionStateInit,
            ReasonCode::StateChangeWithSessionManagementCommands,
        )
    }

    pub fn set_app_config(&mut self, app_config: AppConfig, now: Instant) {
        let old_interval = self.ranging_interval();
        self.app_config = app_config;
        let new_interval = self.ranging_interval();
        if new_interval != old_interval
            && let Some(deadline) = self.next_ranging_at
        {
            self.next_ranging_at = Some(
                deadline
                    .checked_sub(old_interval)
                    .map_or(now + new_interval, |last| (last + new_interval).max(now)),
            );
        }
    }

    pub fn ranging_interval_ms(&self) -> u32 {
        self.app_config
            .ranging_duration()
            .saturating_mul(self.app_config.block_stride())
    }

    fn ranging_interval(&self) -> Duration {
        Duration::from_millis(u64::from(self.ranging_interval_ms()))
    }

    pub fn next_ranging_at(&self) -> Option<Instant> {
        self.next_ranging_at
    }

    pub fn start_ranging(&mut self, now: Instant) {
        self.next_ranging_at = Some(now + self.ranging_interval());
    }

    pub fn poll_ranging(&mut self, now: Instant) -> bool {
        let Some(deadline) = self.next_ranging_at else {
            return false;
        };
        if now < deadline {
            return false;
        }
        let interval = self.ranging_interval();
        let next = deadline + interval;
        self.next_ranging_at = Some(if next > now { next } else { now + interval });
        true
    }

    pub fn stop_ranging(&mut self) {
        self.next_ranging_at = None;
        self.sequence_number = 0;
        self.ranging_count = 0;
        self.in_range_peers.clear();
        self.clear_data();
    }

    pub fn has_reached_max_measurements(&self) -> bool {
        let max_measurements = u32::from(self.app_config.max_number_of_measurements());
        max_measurements != 0 && self.ranging_count >= max_measurements
    }

    pub fn advance_ccc_last_sts_index_used(&mut self) {
        if self.app_config.is_ccc_or_aliro() {
            self.ccc_last_sts_index_used = Some(match self.ccc_last_sts_index_used {
                Some(last) => last.wrapping_add(1),
                None => self.app_config.sts_index(),
            });
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::packets::uci;

    const TEST_SESSION_ID: u32 = 42;
    const TEST_DEVICE_HANDLE: usize = 7;
    const BASE_DURATION_MS: u32 = 120;
    const BASE_DURATION_MS_LE: [u8; 4] = [0x78, 0x00, 0x00, 0x00];
    const STRIDE_1_INTERVAL_MS: u64 = 240;
    const STRIDE_2_INTERVAL_MS: u32 = 360;
    const MISSED_INTERVAL_NOW_MS: u64 = 600;
    const RESCHEDULE_ELAPSED_MS: u64 = 25;

    fn make_session(role: uci::DeviceRole, dev_type: uci::DeviceType, stride: u8) -> Session {
        let mut session = Session::new(
            TEST_SESSION_ID,
            SessionType::FiraRangingSession,
            TEST_DEVICE_HANDLE,
        );
        session
            .app_config
            .set(uci::AppConfigTlvType::DeviceRole, &[role as u8])
            .unwrap();
        session
            .app_config
            .set(uci::AppConfigTlvType::DeviceType, &[dev_type as u8])
            .unwrap();
        session
            .app_config
            .set(uci::AppConfigTlvType::RangingDuration, &BASE_DURATION_MS_LE)
            .unwrap();
        session
            .app_config
            .set(uci::AppConfigTlvType::BlockStrideLength, &[stride])
            .unwrap();
        session
    }

    #[test]
    fn block_stride_extends_controller_interval() {
        let controller = make_session(uci::DeviceRole::Initiator, uci::DeviceType::Controller, 2);
        assert_eq!(controller.ranging_interval_ms(), STRIDE_2_INTERVAL_MS);
    }

    #[test]
    fn block_stride_ignored_for_controlee() {
        let controlee = make_session(uci::DeviceRole::Responder, uci::DeviceType::Controlee, 2);
        assert_eq!(controlee.ranging_interval_ms(), BASE_DURATION_MS);
    }

    #[test]
    fn poll_ranging_advances_deadline_after_expiry() {
        let mut session = make_session(uci::DeviceRole::Initiator, uci::DeviceType::Controller, 1);
        assert_eq!(session.ranging_interval_ms(), STRIDE_1_INTERVAL_MS as u32);

        let t0 = Instant::now();
        session.start_ranging(t0);
        let first_deadline = t0 + Duration::from_millis(STRIDE_1_INTERVAL_MS);
        assert!(!session.poll_ranging(first_deadline - Duration::from_millis(1)));
        assert!(session.poll_ranging(first_deadline));
        assert_eq!(
            session.next_ranging_at(),
            Some(t0 + Duration::from_millis(2 * STRIDE_1_INTERVAL_MS))
        );
    }

    #[test]
    fn poll_ranging_catches_up_after_missed_interval() {
        let mut session = make_session(uci::DeviceRole::Initiator, uci::DeviceType::Controller, 1);
        let t0 = Instant::now();
        session.start_ranging(t0);

        let late = t0 + Duration::from_millis(MISSED_INTERVAL_NOW_MS);
        assert!(session.poll_ranging(late));
        assert_eq!(
            session.next_ranging_at(),
            Some(late + Duration::from_millis(STRIDE_1_INTERVAL_MS))
        );
    }

    #[test]
    fn set_app_config_reschedules_next_ranging_deadline() {
        let mut session = make_session(uci::DeviceRole::Initiator, uci::DeviceType::Controller, 1);
        let t0 = Instant::now();
        session.start_ranging(t0);

        let mut updated = session.app_config.clone();
        updated
            .set(uci::AppConfigTlvType::BlockStrideLength, &[0])
            .unwrap();
        session.set_app_config(updated, t0 + Duration::from_millis(RESCHEDULE_ELAPSED_MS));

        assert_eq!(session.ranging_interval_ms(), BASE_DURATION_MS);
        assert_eq!(
            session.next_ranging_at(),
            Some(t0 + Duration::from_millis(u64::from(BASE_DURATION_MS)))
        );
    }
}
