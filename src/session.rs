//! ## Specifications
//! - [MAC] FiRa Consortium UWB MAC Technical Requirements
//! - [UCI] FiRa Consortium UWB Command Interface Generic Technical specification

use crate::packets::uci::{self, *};
use crate::{AppConfig, DlTdoaMeasurement, MacAddress, UciPacket};
use bytes::{Bytes, BytesMut};
use pdl_runtime::Packet;
use std::collections::HashSet;
use std::time::{Duration, Instant};

pub struct DataTransfer {
    pub sequence_number: u16,
    pub dst_mac_address: MacAddress,
    pub payload: Bytes,
    pub tx_count: u8,
}

impl DataTransfer {
    fn new(
        sequence_number: u16,
        dst_mac_address: u64,
        mac_address_mode: MacAddressMode,
        payload: Bytes,
    ) -> Option<Self> {
        let dst_mac_address = match mac_address_mode {
            MacAddressMode::Mode0 => u16::try_from(dst_mac_address)
                .ok()
                .map(|addr| MacAddress::Short(addr.to_le_bytes()))?,
            MacAddressMode::Mode2 => MacAddress::Extended(dst_mac_address.to_le_bytes()),
            MacAddressMode::Mode1 => return None,
        };
        Some(Self {
            sequence_number,
            dst_mac_address,
            payload,
            tx_count: 0,
        })
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
enum DlTdoaRangingRounds {
    Tag(Vec<u8>),
    Anchor(Vec<uci::DtAnchorRangingRound>),
}

pub struct Session {
    /// cf. [UCI] 7.1
    pub state: SessionState,
    /// cf. [UCI] 7.2 Table 13: 4 octets unique random number generated by application
    id: u32,
    device_handle: usize,
    pending_data: BytesMut,
    pub data_transfer: Option<DataTransfer>,

    pub session_type: SessionType,
    pub sequence_number: u32,
    pub ranging_count: u32,
    dl_tdoa_rounds: Option<DlTdoaRangingRounds>,
    pub app_config: AppConfig,
    pub in_range_peers: HashSet<MacAddress>,
    next_ranging_at: Option<Instant>,
}

impl Session {
    pub fn new(id: u32, session_type: SessionType, device_handle: usize) -> Self {
        Self {
            state: SessionState::SessionStateDeinit,
            id,
            device_handle,
            pending_data: BytesMut::new(),
            data_transfer: None,
            session_type,
            sequence_number: 0,
            ranging_count: 0,
            dl_tdoa_rounds: None,
            app_config: AppConfig::new(session_type),
            in_range_peers: HashSet::new(),
            next_ranging_at: None,
        }
    }

    pub fn dt_tag_active_rounds(&self) -> &[u8] {
        match &self.dl_tdoa_rounds {
            Some(DlTdoaRangingRounds::Tag(rounds)) => rounds.as_slice(),
            _ => &[],
        }
    }

    pub fn dt_anchor_ranging_rounds(&self) -> &[uci::DtAnchorRangingRound] {
        match &self.dl_tdoa_rounds {
            Some(DlTdoaRangingRounds::Anchor(rounds)) => rounds.as_slice(),
            _ => &[],
        }
    }

    pub fn set_dt_tag_ranging_rounds(&mut self, round_indexes: Vec<u8>) {
        self.dl_tdoa_rounds = Some(DlTdoaRangingRounds::Tag(round_indexes));
    }

    pub fn set_dt_anchor_ranging_rounds(&mut self, rounds: Vec<uci::DtAnchorRangingRound>) {
        self.dl_tdoa_rounds = Some(DlTdoaRangingRounds::Anchor(rounds));
    }

    pub fn missing_dl_tdoa_rounds_reason(&self) -> Option<ReasonCode> {
        match self.app_config.dl_tdoa_role()? {
            uci::DeviceRole::DtAnchor if self.dt_anchor_ranging_rounds().is_empty() => {
                Some(ReasonCode::ErrorDtAnchorRangingRoundsNotConfigured)
            }
            uci::DeviceRole::DtTag if self.dt_tag_active_rounds().is_empty() => {
                Some(ReasonCode::ErrorDtTagRangingRoundsNotConfigured)
            }
            _ => None,
        }
    }

    #[must_use]
    pub fn set_state(
        &mut self,
        session_state: SessionState,
        reason_code: ReasonCode,
    ) -> Option<SessionStatusNtf> {
        if session_state == self.state {
            return None;
        }

        self.state = session_state;
        Some(SessionStatusNtf {
            session_token: self.id,
            session_state,
            reason_code: reason_code.into(),
        })
    }

    pub fn get_dst_mac_address(&self) -> impl Iterator<Item = MacAddress> + '_ {
        self.app_config.dst_mac_address()
    }

    pub fn is_session_data_transfer_status_ntf_enabled(&self) -> bool {
        self.app_config.session_data_transfer_status_ntf_config()
            != uci::SessionDataTransferStatusNtfConfig::Disable
    }

    pub fn supports_data_transfer(&self) -> bool {
        matches!(
            self.session_type,
            SessionType::FiraRangingAndInBandDataSession | SessionType::FiraDataTransferSession
        )
    }

    pub fn can_start_data_transfer(&self) -> bool {
        self.state == SessionState::SessionStateActive
            && self.supports_data_transfer()
            && self.app_config.can_start_data_transfer()
    }

    pub fn can_receive_data_transfer(&self, dst_mac_address: MacAddress) -> bool {
        self.state == SessionState::SessionStateActive
            && self.supports_data_transfer()
            && self.app_config.can_receive_data_transfer()
            && self.app_config.device_mac_address() == Some(dst_mac_address)
    }

    pub fn clear_data(&mut self) {
        self.pending_data.clear();
        self.data_transfer = None;
    }

    pub fn has_pending_data(&self) -> bool {
        !self.pending_data.is_empty()
    }

    pub fn session_type(&self) -> SessionType {
        self.session_type
    }

    pub fn is_supported_session_type(&self) -> bool {
        matches!(
            self.session_type,
            SessionType::FiraRangingSession
                | SessionType::FiraRangingAndInBandDataSession
                | SessionType::FiraDataTransferSession
                | SessionType::Ccc
                | SessionType::Aliro
        )
    }

    pub fn session_state(&self) -> SessionState {
        self.state
    }

    #[must_use]
    pub fn init(&mut self) -> Option<SessionStatusNtf> {
        self.set_state(
            SessionState::SessionStateInit,
            ReasonCode::StateChangeWithSessionManagementCommands,
        )
    }

    pub fn set_app_config(&mut self, app_config: AppConfig) {
        let old_interval = self.ranging_interval();
        self.app_config = app_config;
        let new_interval = self.ranging_interval();
        if new_interval != old_interval
            && let Some(deadline) = self.next_ranging_at
        {
            let now = Instant::now();
            self.next_ranging_at = Some(
                deadline
                    .checked_sub(old_interval)
                    .map_or(now + new_interval, |last| (last + new_interval).max(now)),
            );
        }
    }

    pub fn ranging_interval_ms(&self) -> u32 {
        self.app_config
            .ranging_duration()
            .saturating_mul(self.app_config.block_stride())
    }

    fn ranging_interval(&self) -> Duration {
        Duration::from_millis(u64::from(self.ranging_interval_ms()))
    }

    pub fn next_ranging_at(&self) -> Option<Instant> {
        self.next_ranging_at
    }

    pub fn start_ranging(&mut self) {
        self.next_ranging_at = Some(Instant::now() + self.ranging_interval());
    }

    pub fn poll_ranging(&mut self, now: Instant) -> bool {
        let Some(deadline) = self.next_ranging_at else {
            return false;
        };
        if now < deadline {
            return false;
        }
        let interval = self.ranging_interval();
        let next = deadline + interval;
        self.next_ranging_at = Some(if next > now { next } else { now + interval });
        true
    }

    pub fn stop_ranging(&mut self) {
        self.next_ranging_at = None;
        self.sequence_number = 0;
        self.ranging_count = 0;
        self.in_range_peers.clear();
        self.clear_data();
    }

    pub fn has_reached_max_measurements(&self) -> bool {
        let max_measurements = u32::from(self.app_config.max_number_of_measurements());
        max_measurements != 0 && self.ranging_count >= max_measurements
    }

    pub fn data_message_snd(
        &mut self,
        data: DataPacket,
    ) -> Result<ControlPacket, pdl_runtime::EncodeError> {
        tracing::debug!("[{}] data_message_snd", self.device_handle);
        let session_token = self.id;
        let uci_sequence_number = self
            .pending_data
            .get(12..)
            .and_then(|bytes| bytes.first_chunk::<2>())
            .or_else(|| {
                data.payload
                    .get(12..)
                    .and_then(|bytes| bytes.first_chunk::<2>())
            })
            .copied()
            .map_or(0, u16::from_le_bytes);

        let status_ntf = |status| {
            SessionDataTransferStatusNtf {
                session_token,
                status,
                tx_count: 1,
                uci_sequence_number,
            }
            .try_into()
        };

        if !self.supports_data_transfer() {
            self.pending_data.clear();
            return status_ntf(
                DataTransferNtfStatusCode::UciDataTransferStatusSessionTypeNotSupported,
            );
        }

        if !self.can_start_data_transfer() {
            self.pending_data.clear();
            return status_ntf(DataTransferNtfStatusCode::UciDataTransferStatusErrorRejected);
        }

        if self.data_transfer.is_some() {
            self.pending_data.clear();
            return status_ntf(
                DataTransferNtfStatusCode::UciDataTransferStatusErrorNoCreditAvailable,
            );
        }

        if data.payload.len() > MAX_DATA_PACKET_PAYLOAD_SIZE
            || (self.pending_data.len() + data.payload.len())
                .saturating_sub(DATA_MESSAGE_SND_HEADER_SIZE)
                > MAX_DATA_MESSAGE_SIZE
        {
            self.pending_data.clear();
            return status_ntf(DataTransferNtfStatusCode::UciDataTransferStatusInvalidFormat);
        }

        self.pending_data.extend_from_slice(&data.payload);
        if data.pbf == PacketBoundaryFlag::Complete {
            let raw_bytes = self.pending_data.split().to_vec();
            let data_packet = DataPacket {
                dpf: DataPacketFormat::DataSnd,
                pbf: PacketBoundaryFlag::Complete,
                mt: MessageType::Data,
                payload: raw_bytes,
            };
            let Ok(DataPacketChild::DataMessageSnd(data_msg_snd)) = data_packet.specialize() else {
                return status_ntf(DataTransferNtfStatusCode::UciDataTransferStatusInvalidFormat);
            };
            let Some(data_transfer) = DataTransfer::new(
                data_msg_snd.data_sequence_number,
                data_msg_snd.destination_address,
                self.app_config.mac_address_mode(),
                data_msg_snd.application_data.into(),
            ) else {
                return status_ntf(DataTransferNtfStatusCode::UciDataTransferStatusInvalidFormat);
            };
            self.data_transfer = Some(data_transfer);
        }

        let credit_availability = if self.data_transfer.is_some() {
            CreditAvailability::CreditNotAvailable
        } else {
            CreditAvailability::CreditAvailable
        };

        SessionDataCreditNtf {
            credit_availability,
            session_token,
        }
        .try_into()
    }

    pub fn encode_dl_tdoa_session_info_ntf(
        &self,
        measurements: Vec<DlTdoaMeasurement>,
    ) -> Option<UciPacket> {
        match self.app_config.mac_address_mode() {
            MacAddressMode::Mode0 => Some(
                ShortMacDlTDoASessionInfoNtf {
                    sequence_number: self.sequence_number,
                    session_token: self.id,
                    rcr_indicator: 0,
                    current_ranging_interval: self.ranging_interval_ms(),
                    dl_tdoa_measurements: measurements
                        .into_iter()
                        .filter_map(|m| match m.mac_address {
                            MacAddress::Short(addr) => Some(ShortAddressDlTdoaRangingMeasurement {
                                mac_address: u16::from_le_bytes(addr),
                                measurement: m.measurement,
                            }),
                            MacAddress::Extended(_) => None,
                        })
                        .collect(),
                }
                .encode_to_vec()
                .expect("failed to encode ShortMacDlTDoASessionInfoNtf"),
            ),
            MacAddressMode::Mode2 => Some(
                ExtendedMacDlTDoASessionInfoNtf {
                    sequence_number: self.sequence_number,
                    session_token: self.id,
                    rcr_indicator: 0,
                    current_ranging_interval: self.ranging_interval_ms(),
                    dl_tdoa_measurements: measurements
                        .into_iter()
                        .filter_map(|m| match m.mac_address {
                            MacAddress::Extended(addr) => {
                                Some(ExtendedAddressDlTdoaRangingMeasurement {
                                    mac_address: u64::from_le_bytes(addr),
                                    measurement: m.measurement,
                                })
                            }
                            MacAddress::Short(_) => None,
                        })
                        .collect(),
                }
                .encode_to_vec()
                .expect("failed to encode ExtendedMacDlTDoASessionInfoNtf"),
            ),
            mode => {
                tracing::warn!("Unsupported MAC address mode {mode:?}");
                None
            }
        }
    }
}
